"""Generate the wins-and-losses table of README.md from the result files, or check it.

    python bench/scoreboard.py            # print the table
    python bench/scoreboard.py --check    # exit 1 if the table in README.md differs from the files
    python bench/scoreboard.py --write    # rewrite the table in README.md between the markers
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from check_claims import R1, ROOT, agent, arena, fmt, get, robust, sweep  # noqa: E402

BEGIN = "<!-- scoreboard:begin (generated by bench/scoreboard.py — do not edit by hand) -->"
END = "<!-- scoreboard:end -->"
OURS, BASE, TIE = "ours", "baseline", "tie"


def winner(ours, base, better, spread=None):
    """better: 'higher' or 'lower'; spread: a difference not larger than this is a tie."""
    if spread is not None and abs(ours - base) <= spread:
        return TIE
    if better == "higher":
        return OURS if ours > base else BASE if base > ours else TIE
    return OURS if ours < base else BASE if base < ours else TIE


def rows():
    """(method, section, metric, baseline, our value, baseline value, winner, note)."""
    A = "AIfa FlyHash (Binary-Flat)"
    S = "Sign-LSH / BQ 1-Bit"
    r = get(R1, "metrics", "recall_10")
    b = get(R1, "baseline_duel", "recall10")
    yield ("FlyHash (30% k-WTA)", "§1", "Recall@10, 50,000 × 1024", "FAISS exact",
           fmt(r, 2, 100) + "%", fmt(b, 0, 100) + "%", winner(r, b, "higher"), "")
    r = get(R1, "metrics", "latency_p50_ms")
    b = get(R1, "baseline_duel", "p50_ms")
    yield ("FlyHash (30% k-WTA)", "§1", "P50 latency, same run", "FAISS exact",
           fmt(r, 1) + " ms", fmt(b, 1) + " ms", winner(r, b, "lower"), "")
    r, b = arena(A, "recall_at_10_pct"), arena(S, "recall_at_10_pct")
    yield ("FlyHash", "§2", "Recall@10, 25,000 × 512", "Sign-LSH",
           fmt(r, 1) + "%", fmt(b, 1) + "%", winner(r, b, "higher"), "")
    r, b = 2048 * 6, 2048 * 512   # из конфигурации: 2048 клеток Кеньона × 6 «когтей» против 2048 × 512 весов
    yield ("FlyHash", "§2", "non-zero projection weights", "Sign-LSH",
           f"{r:,}", f"{b:,}", winner(r, b, "lower"), "sparser, but see the recall row above")
    best = max((2, 6, 7, 8, 10, 16), key=sweep)
    r, b = sweep(6), sweep(best)
    yield ("fly wiring, d = 6", "§3", "Recall@10", f"best of the sweep, d = {best}",
           fmt(r, 1) + "%", fmt(b, 1) + "%", winner(r, b, "higher"), "")
    for ours, base in (("acr_apl_cann_cx_as_shipped", "pinned_greedy"),
                       ("acr_full_fixed", "pinned_greedy_plus_repulsion")):
        r, b = agent(ours, "success_rate_mean"), agent(base, "success_rate_mean")
        sd = max(agent(ours, "success_rate_std"), agent(base, "success_rate_std"))
        label = {"acr_apl_cann_cx_as_shipped": "ACR as shipped (APL + CANN + CX)",
                 "acr_full_fixed": "full ACR + bilateral verifier"}[ours]
        base_label = {"pinned_greedy": "standard agent, goal pinned",
                      "pinned_greedy_plus_repulsion": "standard + visited-link memory"}[base]
        yield (label, "§4", "task success", base_label,
               f"{fmt(r, 1, 100)}% ± {fmt(agent(ours, 'success_rate_std'), 1, 100)}",
               f"{fmt(b, 1, 100)}% ± {fmt(agent(base, 'success_rate_std'), 1, 100)}",
               winner(r, b, "higher", spread=sd), "tie = within one standard deviation")
    r, b = robust(0.5, "flyhash_recall10"), robust(0.5, "signlsh_recall10")
    yield ("FlyHash", "§5", "Recall@10 with 50% dropout", "Sign-LSH",
           fmt(r, 1, 100) + "%", fmt(b, 1, 100) + "%", winner(r, b, "higher"), "")
    e = get("results/neuromorphic_energy_result.json", "metrics", "energy_efficiency_multiplier")
    yield ("sparse energy model", "§7", "operations per query", "dense FP16",
           fmt(e, 1) + "× fewer", "1×", winner(1 / e, 1.0, "lower"), "operation-count model, not a wattmeter")


def table():
    rs = list(rows())
    out = ["| Our method | § | Metric | Baseline | Ours | Baseline | Who won | Note |",
           "|---|---|---|---|---:|---:|---|---|"]
    for m, sec, metric, base, ov, bv, w, note in rs:
        shown = {OURS: "**ours**", BASE: "**baseline**", TIE: "tie"}[w]
        out.append(f"| {m} | {sec} | {metric} | {base} | {ov} | {bv} | {shown} | {note} |")
    n = {k: sum(1 for x in rs if x[6] == k) for k in (OURS, BASE, TIE)}
    out.append("")
    out.append(f"Ours wins {n[OURS]} of {len(rs)} comparisons, the baseline wins {n[BASE]}, {n[TIE]} "
               f"{'is a tie' if n[TIE] == 1 else 'are ties'}. Every value comes from the file of its section; the "
               f"rule for each winner (higher or lower is better, a tie within one standard deviation) is in "
               f"`bench/scoreboard.py`, and `python bench/scoreboard.py --check` fails if this table no longer "
               f"matches the files.")
    return "\n".join(out)


def block():
    return f"{BEGIN}\n{table()}\n{END}"


def readme_block(text):
    if BEGIN not in text or END not in text:
        return None
    return text[text.index(BEGIN):text.index(END) + len(END)]


def main(argv=None):
    argv = sys.argv[1:] if argv is None else argv
    if hasattr(sys.stdout, "reconfigure"):
        try:
            sys.stdout.reconfigure(encoding="utf-8")
        except Exception:
            pass
    path = os.path.join(ROOT, "README.md")
    with open(path, encoding="utf-8", newline="") as fh:
        text = fh.read()
    if "--write" in argv:
        old = readme_block(text)
        if old is None:
            raise SystemExit("README.md has no scoreboard markers")
        new = block().replace("\n", "\r\n") if "\r\n" in text else block()   # концы строк — как у самого файла
        with open(path, "w", encoding="utf-8", newline="") as fh:
            fh.write(text.replace(old, new))
        print("README.md: scoreboard rewritten")
        return 0
    if "--check" in argv:
        ok = readme_block(text.replace("\r\n", "\n")) == block()
        print("scoreboard matches the result files" if ok else "SCOREBOARD DIFFERS from the result files — "
              "run python bench/scoreboard.py --write and review the diff")
        return 0 if ok else 1
    print(table())
    return 0


if __name__ == "__main__":
    sys.exit(main())
